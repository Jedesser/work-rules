#!/usr/bin/env python3
"""Хук ДО вызова Agent/Task — предполётная проверка ревьюера.

Экономический, а не охранный слой. Отказывает в ЗАПУСКЕ ревьюера, если
дерево, которое он будет смотреть, пустое относительно точки ветвления:
такой прогон может выписать расписку только на «отпечаток ничего», гейт
её всё равно отвергнет, а токены уже потрачены.

Причина у пустого дерева почти всегда одна из двух:
  * сессия сидит не в той рабочей копии (например, в общей, которая
    всегда чистая) — лечится переходом в нужную;
  * все изменения лежат в новых файлах, ещё не добавленных в индекс —
    `git diff` их не видит, лечится `git add`, а не переходом.

Проверка использует ТУ ЖЕ функцию отпечатка, что и писатель расписок.
Две независимые реализации «что такое пусто» разъедутся, и тогда охрана
начнёт отказывать в законных прогонах.

Падает ОТКРЫТО при любой неопределённости: не ревьюер, сломался git,
нет базовой ветки — запуск разрешается. Блокирует только тогда, когда
уверена.

Регистрация: PreToolUse, matcher "Agent|Task".
"""

from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "lib"))
import gatelib as G  # noqa: E402


def main() -> int:
    data = G.read_hook_input()
    if str(data.get("tool_name") or "") not in ("Agent", "Task"):
        return 0
    tool_input = data.get("tool_input") or {}
    if not isinstance(tool_input, dict):
        return 0

    name = G.detect_subagent(tool_input)
    if not name:
        return 0

    work_dir = G.resolve_work_dir(data.get("cwd"))
    diff_sha = G.compute_diff_sha(work_dir)
    if diff_sha != G.EMPTY_DIFF_SHA:
        return 0

    return G.block(
        f"🛑 Предполётная проверка: не запускаю `{name}`.\n\n"
        f"Дерево, которое он будет смотреть, пустое относительно точки ветвления:\n"
        f"    Дерево:  {work_dir}\n"
        f"    Дифф:    <пусто>\n\n"
        "Такой прогон не сможет выписать годную расписку — гейт её отвергнет, "
        "а токены будут потрачены впустую.\n\n"
        "Проверьте два варианта:\n"
        "  1. Сессия не в той рабочей копии — перейдите в ту, где живут изменения\n"
        "     (`git worktree list` покажет все).\n"
        "  2. Новые файлы не добавлены в индекс — `git add` их, `git diff` не видит\n"
        "     файлы, о которых git ещё не знает.\n\n"
        "Если дерево действительно должно быть пустым — ревьюить нечего, "
        "и запускать ревьюера не нужно."
    )


if __name__ == "__main__":
    try:
        sys.exit(main())
    except Exception:
        # Охрана не имеет права ломать законный прогон из-за своей же ошибки.
        sys.exit(0)
